"""Publish the generated vocabulary to WordPress and verify its public readback."""
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass
from datetime import datetime, timezone
import hashlib
import html
import json
import os
from pathlib import Path
import re
import subprocess
import time

from bs4 import BeautifulSoup
from dotenv import load_dotenv
import requests
from requests.auth import HTTPBasicAuth


@dataclass(frozen=True)
class Term:
    name: str
    kind: str
    description: str

    @property
    def text(self):
        return (f"{self.kind}, {self.description}" if self.description else
                f"No Description has been defined for the {self.kind} '{self.name}' in GitHub")


def load_terms(path):
    document = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    terms = []
    for key, kind in (("Nouns", "Noun"), ("Verbs", "Verb")):
        for item in document[key]:
            description = item.get("Description") or []
            if not isinstance(description, list):
                raise ValueError(f"Invalid description for {item['Name']}")
            terms.append(Term(item["Name"], kind, "\n".join(description).strip()))
    if not terms or len({t.name for t in terms}) != len(terms):
        raise ValueError("Empty vocabulary or duplicate term names")
    return terms


def normalized(text):
    # WordPress wptexturize changes straight quotation marks in rendered prose.
    # Compare content while ignoring that presentation-only transformation.
    text = text.translate(str.maketrans({"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2026": "..."}))
    return " ".join(text.split())


def title_of(item):
    return html.unescape(BeautifulSoup(item["title"]["rendered"], "html.parser").get_text()).strip()


def matches(item, term, category):
    paragraph = BeautifulSoup(item["content"]["rendered"], "html.parser").find("p")
    return (title_of(item) == term.name and item.get("status") == "publish" and
            category in item.get("glossary-categories", []) and paragraph is not None and
            normalized(paragraph.get_text(" ")) == normalized(term.text))


def payload(term, category, commit, committed_at):
    # Escape source prose as text; do not execute HTML/scripts from a definition.
    description = html.escape(term.text).replace("\n", "<br>\n")
    digest = hashlib.sha256(term.text.encode("utf-8")).hexdigest()
    content = (f"<p>{description}</p>\n"
               f'<p><i>Content autogenerated from <a href="https://github.com/D-WIS/DDHub-Semantic-Interoperability/commit/{commit}">GitHub</a></i></p>\n'
               f'<div style="display: none;" id="github_modified_date">{committed_at}</div>\n'
               f'<div style="display: none;" id="github_content_hash">{digest}</div>')
    return {"title": term.name, "content": content, "excerpt": f"<p>{description}</p>",
            "status": "publish", "glossary-categories": [category]}


class WordPress:
    def __init__(self, base_url, user=None, password=None, rest_route=True):
        self.base = base_url.rstrip("/") + "/"
        self.auth = HTTPBasicAuth(user, password) if password else None
        self.rest_route = rest_route

    def request(self, method, endpoint, *, params=None, data=None):
        url = self.base + ("?rest_route=" + endpoint if self.rest_route else "wp-json" + endpoint)
        # Retrying GETs and replacement writes to a known ID is safe. Never blindly
        # repeat a creation after a timeout: the server may already have created it.
        attempts = 3 if method == "GET" or re.search(r"/glossary/\d+$", endpoint) else 1
        for attempt in range(attempts):
            try:
                response = requests.request(method, url, auth=self.auth, params=params,
                                            json=data, timeout=(10, 45))
                expected = (200, 201) if method == "POST" else (200,)
                if response.status_code not in expected:
                    if response.status_code in (429, 500, 502, 503, 504) and attempt + 1 < attempts:
                        time.sleep(2 ** attempt)
                        continue
                    raise RuntimeError(f"{method} {endpoint}: HTTP {response.status_code}")
                try:
                    return response.json()
                except ValueError as error:
                    raise RuntimeError(f"{method} {endpoint}: expected a JSON response") from error
            except requests.exceptions.SSLError as error:
                raise RuntimeError(f"{method} {endpoint}: TLS certificate verification failed") from error
            except (requests.Timeout, requests.ConnectionError) as error:
                if attempt + 1 == attempts:
                    raise RuntimeError(f"{method} {endpoint}: request timed out or connection failed") from error
                time.sleep(2 ** attempt)

    def category(self):
        categories = self.request("GET", "/wp/v2/glossary-categories", params={"per_page": 100})
        found = [c["id"] for c in categories if c["name"] == "Vocabulary"]
        if len(found) != 1:
            raise RuntimeError("Expected exactly one Vocabulary category")
        return found[0]

    def glossary(self, category):
        result = {}
        offset = 0
        while True:
            items = self.request("GET", "/wp/v2/glossary", params={
                "per_page": 100, "offset": offset, "orderby": "id", "order": "asc",
                "glossary-categories": category,
                "_fields": "id,title,content,status,glossary-categories,link"})
            if not isinstance(items, list):
                raise RuntimeError("Expected a glossary list")
            for item in items:
                name = title_of(item)
                if name in result:
                    # Preserve existing URLs. Repair all copies in place rather than
                    # silently selecting one or deleting a published entry.
                    result[name].setdefault("_duplicates", []).append(item)
                else:
                    result[name] = item
            print(f"Read {len(result)} published terms", flush=True)
            if len(items) < 100:
                return result
            offset += len(items)


def publish_one(client, term, existing, category, commit, committed_at, force=False):
    duplicate_updates = []
    if existing is not None:
        duplicate_updates = [publish_one(client, term, copy, category, commit, committed_at, force)
                             for copy in existing.get("_duplicates", [])]
    if existing is not None and not force and matches(existing, term, category):
        return "updated" if "updated" in duplicate_updates else "unchanged"
    endpoint = "/wp/v2/glossary" + (f"/{existing['id']}" if existing else "")
    value = payload(term, category, commit, committed_at)
    try:
        saved = client.request("POST", endpoint, data=value)
    except RuntimeError:
        if existing is not None:
            raise
        # Resolve ambiguous creation by reading the exact title before any rerun.
        found = client.request("GET", "/wp/v2/glossary", params={
            "search": term.name, "per_page": 100, "glossary-categories": category})
        exact = [item for item in found if title_of(item) == term.name]
        if len(exact) != 1 or not matches(exact[0], term, category):
            raise
        saved = exact[0]
    if not matches(saved, term, category):
        raise RuntimeError(f"Write response did not preserve the description/category for {term.name}")
    return "updated" if existing else "created"


def verify(terms, published, category):
    return [term.name for term in terms if term.name not in published or
            any(not matches(item, term, category) for item in
                [published[term.name]] + published[term.name].get("_duplicates", []))]


def main():
    load_dotenv()
    if os.getenv("FORCE_DELETION", "false").lower() in ("true", "1", "yes"):
        raise ValueError("Bulk glossary deletion is not supported; publish updates in place")
    source = Path(os.getenv("SOURCE_PATH", "../auto-generated/md")).resolve().parent / "json" / "DWISVocabulary.json"
    terms = load_terms(source)
    verify_only = os.getenv("VERIFY_ONLY", "false").lower() in ("true", "1", "yes")
    password = os.getenv("WORDPRESS_APPLICATION_PASSWORD")
    if not verify_only and not password:
        raise ValueError("WORDPRESS_APPLICATION_PASSWORD is required for publication")
    repository = next(p for p in source.parents if (p / ".git").exists())
    revision = subprocess.check_output(["git", "-c", f"safe.directory={repository.as_posix()}",
        "log", "-1", "--format=%H%n%cI", "--", str(source)], cwd=repository, text=True).splitlines()
    if len(revision) != 2:
        raise ValueError("Cannot identify the generated vocabulary commit")
    client = WordPress(os.environ["WORDPRESS_URL"], os.getenv("WORDPRESS_USER"), password,
                      os.getenv("WORDPRESS_USE_REST_ROUTE", "true").lower() != "false")
    category = client.category()
    existing = client.glossary(category)
    print(f"Source: {len(terms)} terms; existing: {len(existing)}; commit: {revision[0]}", flush=True)
    report = {"source_commit": revision[0], "total": len(terms), "created": 0,
              "updated": 0, "unchanged": 0, "failed": [], "mismatched": [],
              "duplicate_titles_preserved": sorted(name for name, item in existing.items() if item.get("_duplicates"))}
    if not verify_only:
        force = os.getenv("FORCE_UPDATE", "false").lower() in ("true", "1", "yes")
        workers = int(os.getenv("WORDPRESS_WORKERS", "2"))
        if not 1 <= workers <= 4:
            raise ValueError("WORDPRESS_WORKERS must be between 1 and 4")
        with ThreadPoolExecutor(max_workers=workers) as executor:
            pending = {executor.submit(publish_one, client, term, existing.get(term.name), category,
                                      revision[0], revision[1], force): term for term in terms}
            for index, future in enumerate(as_completed(pending), 1):
                term = pending[future]
                try:
                    outcome = future.result()
                    report[outcome] += 1
                    if outcome != "unchanged":
                        print(f"{index}/{len(terms)} {outcome}: {term.name}", flush=True)
                except Exception as error:
                    report["failed"].append(term.name)
                    print(f"FAILED {term.name}: {error}", flush=True)
                if index % 100 == 0:
                    print(f"Progress {index}/{len(terms)}: updated={report['updated']}, created={report['created']}, unchanged={report['unchanged']}, failed={len(report['failed'])}", flush=True)
        # Independent GET readback catches missing or sanitized writes, not just HTTP success.
        existing = client.glossary(category)
    report["mismatched"] = verify(terms, existing, category)
    report["verified"] = not report["failed"] and not report["mismatched"]
    report["checked_at_utc"] = datetime.now(timezone.utc).isoformat()
    Path(os.getenv("REPORT_PATH", "publication-report.json")).write_text(json.dumps(report, indent=2), encoding="utf-8")
    summary = {**report, "mismatched": len(report["mismatched"]), "failed": len(report["failed"])}
    print(json.dumps(summary, indent=2), flush=True)
    if not report["verified"]:
        raise RuntimeError("Glossary publication/readback verification failed; see publication report")


if __name__ == "__main__":
    main()
